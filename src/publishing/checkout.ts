import { randomUUID } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { FdgError } from '../contracts/errors.js';
import type { Target } from '../contracts/publishing.js';
import type { InstanceContext } from '../instance/index.js';
import { git } from '../platform/git.js';
import { hash } from '../platform/hash.js';
import { resource } from '../platform/resources.js';
import { completeArtifact, markArtifact, pruneArtifacts } from '../platform/retention.js';
import { ensureSafe, tree } from './filesystem.js';
import type { Manifest } from './targets.js';
import { manifestSchema, ownerFile, validEntry } from './targets.js';
import { remoteHead } from './transport.js';
export async function checkout(config: InstanceContext, target: Target, signal?: AbortSignal) {
  if (target.repository.startsWith('-') || /^(ext|file):/i.test(target.repository)) throw new FdgError('CONFIG_INVALID', 'Unsupported repository transport');
  const root = join(config.paths.cache, 'publish', target.id + '-' + randomUUID());
  await mkdir(root, { recursive: true, mode: 0o700 });
  await markArtifact(root, 'publish', config.instanceId, target.id);
  const dispose = async (succeeded = true) => {
    await completeArtifact(root, succeeded);
    await pruneArtifacts(join(config.paths.cache, 'publish'), 'publish', config.instanceId, 3, 7);
  };
  try {
    await git(['init', '--quiet'], root, signal);
    // Ownership hashes describe generated bytes. Host Git newline preferences
    // must not rewrite them when staging or checking out a managed repository.
    await git(['config', 'core.autocrlf', 'false'], root, signal);
    await git(['config', 'core.eol', 'lf'], root, signal);
    await git(['remote', 'add', 'origin', target.repository], root, signal);
    const head = await remoteHead(root, target, git, signal);
    if (head) {
      await git(['fetch', '--no-tags', 'origin', target.branch], root, signal);
      await git(['checkout', '--detach', 'FETCH_HEAD'], root, signal);
    } else await git(['checkout', '--orphan', 'fdg-initial'], root, signal);
    // Git mode checks catch symlinks even on Windows checkouts without symlink privileges.
    if (head)
      for (const line of (
        await git(['ls-tree', '-r', 'HEAD', '--', target.managedPrefix, ...target.auxiliaryFiles], root, signal)
      )
        .split('\n')
        .filter(Boolean))
        if (!/^100(?:644|755) /.test(line))
          throw new FdgError('UNSAFE_PATH', 'Target contains a symlink or submodule');
    const prefix = await ensureSafe(root, target.managedPrefix),
      files = await tree(prefix);
    let manifest: Manifest | undefined;
    if (files[ownerFile]) {
      try {
        manifest = manifestSchema.parse(JSON.parse(files[ownerFile]!.toString()));
      } catch {
        throw new FdgError('MANIFEST_INVALID', 'Invalid owner manifest');
      }
      if (Object.keys(manifest.entries).some((path) => !validEntry(path, target)))
        throw new FdgError('MANIFEST_INVALID', 'Manifest contains an unsafe managed path');
    }
    delete files[ownerFile];
    for (const path of target.auxiliaryFiles) {
      const full = await ensureSafe(root, path);
      if (existsSync(full)) files['@/' + path] = await readFile(full);
    }
    if (target.format === 'jekyll')
      for (const name of ['Gemfile', 'Gemfile.lock']) {
        const file = await ensureSafe(root, name);
        if (existsSync(file) && hash(await readFile(file)) !== hash(await readFile(resource('ui', name))))
          throw new FdgError(
            'UNTRUSTED_UI_DEPENDENCIES',
            'Target ' + name + ' differs from the bundled UI dependencies',
          );
      }
    return { root, prefix, head, files, manifest, dispose };
  } catch (error) { await dispose(false); throw error; }
}
export function owned(
  config: InstanceContext,
  target: Target,
  manifest: Manifest | undefined,
  files: Record<string, Buffer>,
): void {
  if (
    (!manifest && Object.keys(files).length) ||
    (manifest && (manifest.instanceId !== config.instanceId || manifest.targetId !== target.id))
  )
    throw new FdgError(
      'TARGET_ADOPTION_REQUIRED',
      'Explicit targets adopt with the inspected head is required',
    );
}
export async function inspectTarget(config: InstanceContext, target: Target) {
  const current = await checkout(config, target);
  try {
    return {
      targetId: target.id,
      head: current.head ?? null,
      owner: current.manifest ?? null,
      files: Object.keys(current.files),
      adoptionRequired: !current.manifest || current.manifest.instanceId !== config.instanceId,
      checkout: current.root,
    };
  } finally { await current.dispose(); }
}
