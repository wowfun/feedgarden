test('cache recipes and paths stay stable; bilingual rendering adds generation identity hints', async () => {
  // Captured from the original sources saved before modularization, not generated by the new implementation.
  const fixture = JSON.parse(await readFile(new URL('../support/fixtures/modularization-contract.json', import.meta.url), 'utf8'));
  const config = configSchema.parse(fixture.config), item = fixture.item as Item;
  assert.equal(summaryKey(item, config.agent, 'fixed-skill-hash'), fixture.expected.summary);
  assert.equal(await taskKey(config.agent, 'transcript', fixture.transcript), fixture.expected.task);
  assert.equal(selectionPolicy(config.sources[0]!), fixture.expected.selection);
  assert.equal(itemPath('hackernews', '2026-10-09', 7), fixture.expected.path);
  assert.equal(renderItem(fixture.record as AcceptedItem, 'en'), fixture.expected.en);
  assert.equal(renderItem(fixture.record as AcceptedItem, 'zh-CN'), fixture.expected.zh);
  // The bundled theme reserves `source` for a URL, not a collector identifier.
  const fields = parse(/^---\n([\s\S]*?)\n---/.exec(fixture.expected.en)![1]!);
  assert.equal(fields.source, undefined);
  assert.equal(fields.feed_source, fixture.record.item.source);
  assert.equal(fields.feed_source_id, fixture.record.item.id);
  const template = parse(await readFile(new URL('../../resources/ui/jekyll-obsidian.yml', import.meta.url), 'utf8'));
  assert.ok(template.website.properties.hidden.includes('feed_source'));
  assert.ok(template.website.properties.hidden.includes('feed_source_id'));
});

test('shared navigation preserves custom locale fields while applying topic and source labels', () => {
  const registry = { version: 1 as const, topics: [{ id: 'coding', name: { en: 'Coding', 'zh-CN': '编程' }, description: 'Tools', aliases: [], deprecated: false, hidden: true }] };
  const previous = { messages: { search: 'Custom search' }, tag_labels: { 'source/foreign': 'External notes', 'custom/note': 'Note', 'topics/coding': 'Stale' }, hidden_tags: ['topics/retired', 'custom/note'], tag_aliases: { 'custom/old': 'custom/note' } };
  for (const locale of ['en', 'zh-CN'] as const) {
    const manifest = localeManifest({ name: locale, tag_labels: { 'source/clippings': 'Clippings' } }, previous, [{ id: 'foreign' }, { id: 'one', name: 'One' }], registry, locale);
    assert.deepEqual(manifest.messages, previous.messages);
    assert.equal(manifest.tag_labels['source/foreign'], 'External notes');
    assert.equal(manifest.tag_labels['source/one'], 'One');
    assert.equal(manifest.tag_labels['topics/coding'], registry.topics[0]!.name[locale]);
    assert.deepEqual(manifest.hidden_tags, ['custom/note', 'topics/coding']);
    assert.equal(manifest.tag_aliases?.['custom/old'], 'custom/note');
    const index = indexPage(locale, { id: 'github' });
    const fields = parse(/^---\n([\s\S]*?)\n---/.exec(index)![1]!);
    assert.equal(fields.title, 'GitHub');
    assert.deepEqual(fields.tab, locale === 'en' ? { id: 'github', order: 12, topics: ['source/github'], layout: 'archive' } : { label: 'GitHub' });
    assert.match(indexPage(locale, { id: 'foreign', name: 'External notes' }), /title: "External notes"/);
  }
});
